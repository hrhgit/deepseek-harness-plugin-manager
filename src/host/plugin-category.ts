/** Classify a package using Harness workspace groups before external origins. */
export function pluginCategory(packageName: string): PluginCategory {
  if (packageName.startsWith('cordis:') || packageName.startsWith('@deepseek-ai/cordis-')) return 'cordis'
  const group = HARNESS_PACKAGE_GROUPS[packageName]
  if (group !== undefined) return group
  if (packageName.startsWith('@deepseek-ai/dsh-')) return 'harness-other'
  return 'community'
}
